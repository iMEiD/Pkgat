-- =============================================================
-- 0029 — مظهر الموقع بيد الأدمن: الوضع الليلي والشكل الزجاجي
--
-- الوضع الليلي موجود في الموقع ويعمل منذ البداية، لكنه كان بيد الزائر
-- وحده: جهازه يقرّر، وزر الشمس/القمر يغيّر. وصاحب الموقع لا يملك أن
-- يقول «موقعي ليلي دائماً» ولا أن يوقف الوضع الليلي إن لم يعجبه.
--
-- وهذا الترحيل يضيف صفّ الإعداد فقط. وقيمه الافتراضية هي الحال الراهن
-- بالضبط (mode=auto, surface=classic)، فتشغيله لا يغيّر شكل الموقع ولا
-- بكسل — التغيير لا يقع إلا حين يضغط الأدمن في /admin/theme.
--
-- surface='classic' يعني: لا شيء إطلاقاً فوق أنماط الموقع الحالية.
-- فالرجوع عن الشكل الجديد ليس «استعادة نسخة» بل إطفاء مفتاح.
-- =============================================================

insert into public.site_settings (key, value, label)
values (
  'appearance',
  '{"mode":"auto","surface":"classic","glass":"medium"}'::jsonb,
  'مظهر الموقع (الوضع الليلي والشكل الزجاجي)'
)
on conflict (key) do nothing;
