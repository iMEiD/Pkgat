-- =============================================================
-- 0033 — «أعمالنا» تعرض أعمال العملاء، ويمكن إطفاؤها
--
-- ثلاث علّات:
--
-- ١) الصفحة اسمها «أعمالنا» وتعرض قوالبنا الجاهزة. والقالب ليس عملاً
--    أُنجز، والزائر يقرأ الصفحة على أنها سجلّ إنجاز — فيراها إنجازاً
--    مصنوعاً. وهذا يضرّ حيث أُريد له أن ينفع.
--
--    والقوالب مبذورة منذ الترحيل ٠٠٠٦ في جدول المعرض نفسه، فتُخفى
--    هنا ولا تُحذف: هي قوالب صالحة يستعملها المحرّر، وحذفها يفقدها.
--
-- ٢) لا سبيل لإطفاء الصفحة. ومنصة قبل إطلاقها لا أعمال لها، فصفحة
--    فارغة اسمها «أعمالنا» أسوأ من غيابها.
--
-- ٣) نصّها يعد بقوالب. فيُعاد إلى ما ستعرضه فعلاً.
-- =============================================================

-- إخفاء القوالب المبذورة من المعرض العام (تبقى صفوفها كما هي)
update public.gallery_items
   set is_published = false
 where image_url like '/templates/%';

insert into public.site_settings (key, value, label) values
  ('gallery_enabled', 'false'::jsonb,
   'إظهار صفحة «أعمالنا» — أطفئها حتى تجمع أعمال عملاء تعرضها')
on conflict (key) do nothing;

update public.site_content
   set value = '"أعمال عملائنا"'::jsonb
 where key = 'gallery.title';

update public.site_content
   set value = '"دعوات حقيقية أُنجزت على بكجات — بتصاميم أصحابها وباركود دخول لكل مدعو."'::jsonb
 where key = 'gallery.subtitle';
