-- 0035 — عنوان المتصفح ووصف الموقع بيد الأدمن
--
-- العنوان الذي يظهر في تبويب المتصفح، وفي نتائج البحث، وفي بطاقة
-- المشاركة على واتساب — كان مكتوباً في الكود. وهو أكثر نصٍّ يُرى:
-- يقرؤه من لم يفتح الموقع بعد.
--
-- ثلاثة مفاتيح:
--
--   common.site_title       عنوان الصفحة الرئيسية وتبويب المتصفح
--   common.title_suffix     ما يُلحق بعناوين بقية الصفحات: «الأسعار · بكجات»
--   common.site_description الوصف في نتائج البحث وبطاقة المشاركة
-- =============================================================

insert into public.site_content (key, page, label, kind, value) values
  ('common.site_title', 'common', 'عنوان الموقع في تبويب المتصفح ونتائج البحث', 'text',
   '"بكجات — لإدارة الفعاليات"'::jsonb),
  ('common.title_suffix', 'common', 'ما يُلحق بعناوين الصفحات الأخرى (مثال: الأسعار · بكجات)', 'text',
   '"بكجات"'::jsonb),
  ('common.site_description', 'common', 'وصف الموقع في نتائج البحث وبطاقة واتساب', 'text',
   '"ارفع دعوتك بأي تصميم، ونولّد باركود دخول فريد لكل مدعو. امسحه على الباب من جوالك واعرف مين حضر لحظة بلحظة."'::jsonb)
on conflict (key) do update set label = excluded.label;
