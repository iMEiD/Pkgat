-- =============================================================
-- 0034 — سطر السعر في البطل يصير نصّاً قابلاً للتعديل
--
-- كان مكتوباً في الكود، فلا يملك الأدمن تغيير صياغته ولا إخفاءه — وهو
-- أظهرُ سطرٍ بعد الأزرار. وكلُّ نصٍّ يراه الزائر ينبغي أن يكون بيد
-- صاحب الموقع لا بيد من كتب الصفحة.
--
-- ورمزان يُستبدلان عند العرض:
--
--   {price} → سعر أرخص باقة فعّالة، مقروءاً من جدول الباقات
--   {free}  → عدد الدعوات المجانية، مقروءاً من الإعدادات
--
-- فيبقى الرقمان صادقين مهما غُيّرت الباقة أو الحصة، ويبقى الكلام حولهما
-- بيد الأدمن. ولو حُذف {price} من النص عُرض النص كما هو.
--
-- وإفراغ الحقل يُخفي السطر كله.
-- =============================================================

insert into public.site_content (key, page, label, kind, value) values
  ('home.hero.price_note', 'home',
   'سطر السعر تحت أزرار البطل — {price} سعر أرخص باقة، {free} عدد الدعوات المجانية. أفرغه لإخفائه',
   'text',
   '"الباقات تبدأ من {price} — وأول {free} دعوات مجاناً قبلها."'::jsonb)
on conflict (key) do update set label = excluded.label;
